export function getTool(id: string): ToolDefinition | undefined {
  return tools.find((t) => t.id === id);
}

/** Grouped by registration order, used by the sidebar and home page */
export function getCategories(): { name: string; tools: ToolDefinition[] }[] {
  const map = new Map<string, ToolDefinition[]>();
  for (const t of tools) {
    const list = map.get(t.category) ?? [];
    list.push(t);
    map.set(t.category, list);
  }
  return [...map].map(([name, tools]) => ({ name, tools }));
}

/** URL slug for a category; derived from the English name in the registry. */
export function categorySlug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function getCategory(slug: string) {
  return getCategories().find((c) => categorySlug(c.name) === slug);
}
