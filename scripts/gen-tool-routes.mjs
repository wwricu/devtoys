// Generate one static route per tool from the registry in lib/tools.ts.
// Each route gets its own client entry, so a tool page ships only that tool's
// chunk instead of every tool in the registry. Routes live under
//   app/[category-slug]/[tool-id]/
// Run after adding a tool:
//   npm run gen:routes
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(join(root, "lib/tools.ts"), "utf8");

const entries = [
  ...source.matchAll(
    /id:\s*"([^"]+)"[\s\S]*?category:\s*"([^"]+)"[\s\S]*?component:\s*"([^"]+)",/g,
  ),
];
if (entries.length === 0) {
  console.error("No registry entries found in lib/tools.ts");
  process.exit(1);
}

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const banner = (id) =>
  `// Generated by scripts/gen-tool-routes.mjs: one static route per tool keeps the\n// page bundle down to that tool. Add tools in lib/tools.ts, then npm run gen:routes.\n// Registry entry "${id}".\n`;

for (const [, id, category, specifier] of entries) {
  const name = specifier.split("/").pop();
  const catSlug = slugify(category);
  const dir = join(root, "app", catSlug, id);
  mkdirSync(dir, { recursive: true });

  writeFileSync(
    join(dir, "entry.tsx"),
    `${banner(id)}"use client";

import ToolShell from "@/components/ToolShell";
import { ToolMount } from "@/lib/toolModule";

export default function ${name}Entry() {
  return (
    <ToolShell id="${id}">
      <ToolMount id="${id}" />
    </ToolShell>
  );
}
`,
  );

  writeFileSync(
    join(dir, "page.tsx"),
    `${banner(id)}import type { Metadata } from "next";
import { toolMetadata } from "@/lib/toolMeta";
import ${name}Entry from "./entry";

/** The shell is prerendered; the tool body is a client-only chunk. */
export const instant = false;

export function generateMetadata(): Metadata {
  return toolMetadata("${id}");
}

export default function ${name}Page() {
  return <${name}Entry />;
}
`,
  );
}

writeFileSync(
  join(root, "lib", "toolPreload.ts"),
  `${banner("chunk warm-up")}
import type { ComponentType } from "react";

export const toolLoaders: Record<string, () => Promise<{ default: ComponentType }>> = {
${entries.map(([, id, , spec]) => `  "${id}": () => import("${spec}"),`).join("\n")}
};
`,
);

console.log(`Wrote ${entries.length} tool routes.`);
